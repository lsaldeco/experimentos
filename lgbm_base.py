plt.ylim(bottom=0)
plt.xlim(0, 30000)

plt.title(
    "Curvas de Ganancia en Millones:  10 Semillas y Ensamble (Octubre 201910)",
    fontsize=13,
    fontweight="bold",
)
plt.xlabel("Cantidad de Envíos (Ordenados por Probabilidad)", fontsize=12)
plt.ylabel("Ganancia Acumulada (Millones)", fontsize=12)
plt.grid(True, linestyle="--", alpha=0.6)
plt.legend(loc="lower right", fontsize=11)
